import {test, expect, monitorFixture} from './fixtures.mjs'

const language = page => page.locator('.language-select select')

test('browser language, saved preference and other tabs stay in sync without losing form edits', async ({browser, baseURL}) => {
  const context = await browser.newContext({baseURL, locale: 'en-GB'})
  try {
    const page = await context.newPage()
    await page.goto('/#/settings')
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('heading', {name: 'Settings', exact: true})).toBeVisible()
    const field = page.locator('.settings-inputs input').first()
    await field.fill('7')
    await language(page).selectOption('zh-CN')
    await expect(field).toHaveValue('7')
    await expect(page.getByRole('heading', {name: '偏好设置', exact: true})).toBeVisible()
    await expect(page).toHaveURL(/#\/settings$/)
    const second = await context.newPage()
    await second.goto('/#/nodes')
    await expect(language(second)).toHaveValue('zh-CN')
    await language(second).selectOption('en')
    await expect(language(page)).toHaveValue('en')
    await expect(field).toHaveValue('7')
    await second.reload()
    await expect(language(second)).toHaveValue('en')
  } finally { await context.close() }
})

test('switching language preserves a real scan and translates its confirmation dialog', async ({page, context}) => {
  let starts = 0
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/scans') starts++ })
  await page.goto('/')
  await page.getByRole('button', {name: /^(开始扫描|重新扫描)$/}).filter({visible: true}).click()
  await language(page).selectOption('en')
  await expect(page.getByText('Scan complete', {exact: true})).toBeVisible()
  expect(starts).toBe(1)
  const id = await page.locator('.profile-scope select').inputValue()
  const names = await page.locator('.node-focus').allTextContents()
  await page.getByRole('button', {name: 'Select JP-Osaka-02', exact: true}).click()
  const dialog = page.getByRole('dialog', {name: 'Confirm node switch'})
  await expect(dialog).toContainText('JP-Osaka-02')
  const second = await context.newPage()
  await second.goto('/#/nodes')
  await language(second).selectOption('zh-CN')
  await expect(page.getByRole('dialog', {name: '确认切换节点'})).toBeVisible()
  await page.getByRole('button', {name: '取消', exact: true}).click()
  await expect(page.locator('.profile-scope select')).toHaveValue(id)
  expect(await page.locator('.node-focus').allTextContents()).toEqual(names)
  expect(starts).toBe(1)
  await second.close()
})

test('monitoring retains selected evidence and translates an existing timeout notice', async ({page}) => {
  await monitorFixture(page, {eventMessage: '节点路径探测失败或超时；未定位具体故障位置'})
  await page.clock.install()
  await page.goto('/#/monitor')
  await page.getByRole('button', {name: '查看当前节点趋势'}).click()
  await page.getByLabel('观测序列').selectOption('series-b')
  await page.clock.runFor(200)
  const chart = await page.locator('path.p95').getAttribute('d')
  await language(page).selectOption('en')
  await expect(page.locator('path.p95')).toHaveAttribute('d', chart)
  await expect(page.locator('.history-heading select')).toHaveValue('series-b')
  await expect(page.locator('.history-panel')).toContainText('JP-Osaka-02')
  await page.getByRole('tab', {name: 'Event timeline', exact: true}).click()
  await expect(page.locator('.event-list')).toContainText('The node-path probe failed or timed out.')
  await page.getByRole('tab', {name: 'Monitor settings', exact: true}).click()
  await page.locator('.storage > summary').click()
  await page.locator('.storage input').first().fill('9')
  await language(page).selectOption('zh-CN')
  await expect(page.locator('.storage input').first()).toHaveValue('9')
  await expect(page.locator('.storage > summary')).toHaveText('存储与保留策略')
  await language(page).selectOption('en')
  await page.getByRole('tab', {name: 'Overview', exact: true}).click()
  await page.route('**/api/v1/monitor?**', () => {})
  await page.clock.runFor(15200)
  const alert = page.locator('.monitor-page > [role="alert"]')
  await expect(alert).toContainText('timed out')
  await expect(alert).toContainText('Last successful')
  await language(page).selectOption('zh-CN')
  await expect(alert).toContainText('读取超时')
  await expect(page.getByRole('button', {name: '查看当前节点趋势'})).toBeVisible()
})

test('both languages fit all routes at 320px and names and filters remain raw', async ({page}, info) => {
  await monitorFixture(page, {eventMessage: '节点路径探测失败或超时；未定位具体故障位置'})
  await page.route('**/api/v1/nodes', async route => {
    const response = await route.fetch()
    const data = await response.json()
    for (const node of data) { node.name = '健康'; node.provider = '扫描失败' }
    await route.fulfill({json: data.slice(0, 1)})
  })
  await page.setViewportSize({width: 320, height: 812})
  await page.goto('/#/nodes')
  await page.getByLabel('搜索节点', {exact: true}).fill('健康')
  await language(page).selectOption('en')
  await expect(page.locator('#catalog-search')).toHaveValue('健康')
  await expect(page.locator('.catalog-node')).toHaveText('健康')
  await expect(page.locator('.catalog tbody')).toContainText('扫描失败')
  for (const locale of ['en', 'zh-CN']) {
    await language(page).selectOption(locale)
    for (const route of ['scan', 'monitor', 'nodes', 'history', 'settings']) {
      await page.locator('nav button').nth(['scan', 'monitor', 'nodes', 'history', 'settings'].indexOf(route)).click()
      await expect(page.locator('main.work > header h1')).not.toBeEmpty()
      if (route === 'settings') await expect(page.locator('.runtime-fields')).toBeVisible()
      if (route === 'monitor') await expect(page.locator('.monitor-node-card').first()).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${locale}/${route}: page overflows`).toBe(true)
      await page.screenshot({path: info.outputPath(`${locale}-${route}-320.png`), fullPage: true, animations: 'disabled'})
    }
  }
})

test('LAN access screen supports both languages even when local storage is disabled', async ({page}) => {
  await page.addInitScript(() => Object.defineProperty(window, 'localStorage', {get() { throw new DOMException('Denied', 'SecurityError') }}))
  await page.route('**/api/v1/**', route => route.fulfill({status: 401, json: {error: 'Unauthorized'}}))
  await page.goto('/')
  await expect(page.locator('.access')).toBeVisible()
  await page.getByLabel('LAN token').fill('local-test-token')
  await language(page).selectOption('en')
  await expect(page.getByRole('button', {name: 'Connect securely'})).toBeEnabled()
  await expect(page.getByLabel('LAN token')).toHaveValue('local-test-token')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
})
